package com.acme.harbor.client.rest

import com.acme.harbor.client.generated.documentservice.DocumentsApi
import com.acme.harbor.client.generated.documentservice.model.RenderRequest
import org.springframework.beans.factory.annotation.Value
import org.springframework.stereotype.Component
import org.springframework.web.client.RestClient

/**
 * Thin wrapper around document-service. PDF rendering is normally requested asynchronously over Kafka
 * (`harbor.reports.render-requested`, see `ReportRenderRequester`); this client downloads finished documents
 * and offers the synchronous `POST /render` fallback.
 *
 * `DocumentsApi` and models are generated by openapi-generator from `api/document-service.yaml`
 * into package `com.acme.harbor.client.generated.documentservice` (not committed).
 */
@Component
class DocumentServiceClient(
    restClientBuilder: RestClient.Builder,
    @Value("\${harbor.external.document-service.base-url}") baseUrl: String,
) {
    private val api = DocumentsApi(restClientBuilder.baseUrl(baseUrl).build())

    fun render(payloadRef: String, correlationId: String, template: String = MEETING_REPORT_TEMPLATE): String =
        api.renderDocument(RenderRequest(template = template, payloadRef = payloadRef, correlationId = correlationId)).documentId

    fun download(documentId: String): ByteArray = api.getDocument(id = documentId).readBytes()

    companion object {
        const val MEETING_REPORT_TEMPLATE = "meeting-report"
    }
}
