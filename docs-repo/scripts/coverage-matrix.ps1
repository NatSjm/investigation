<#
.SYNOPSIS
  Documentation analytics without reading code: for every feature spec, which business rules (BR-<ID>-<n>) are
  cited by a story acceptance criterion (work-items/<ID>.yml, `rule:`) and by a Gherkin scenario
  (test-design/features/<ID>.feature, `@BR-<ID>-<n>`), plus trust badge and staleness. Writes an OKF Document to
  generated/analytics/coverage-matrix.md (and JSON next to it) so the analyst agent answers status questions from it.
.EXAMPLE
  .\coverage-matrix.ps1                # all specs
  .\coverage-matrix.ps1 -Scope P1      # one context prefix
#>
param(
    [string]$Scope = '',
    [string]$Out = 'generated/analytics/coverage-matrix.md'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Utf8 = [Text.UTF8Encoding]::new($false)
$repo = Split-Path $PSScriptRoot -Parent
$now = [DateTime]::UtcNow
function Read-File([string]$p) { if (Test-Path $p) { [IO.File]::ReadAllText($p, $Utf8) } else { '' } }
function Get-Fm([string]$t) { if ($t -match '(?s)\A﻿?---\r?\n(.*?)\r?\n---') { $Matches[1] } else { '' } }
function Get-Val([string]$fm, [string]$k) { if ($fm -match "(?m)^$k`:\s*(.+?)\s*$") { ($Matches[1] -replace '\s+#.*$', '').Trim().Trim('"') } else { '' } }
function Get-Badge([string]$fm) {
    $b = @(); $s = Get-Val $fm 'status'; if ($s -and $s -ne 'stable') { $b += $s }
    if ($fm -match '(?m)^verified:') { $b += $(if ($fm -match 'verified:[\s\S]*?by:\s*human:') { 'human-reviewed' } else { 'machine-confirmed' }) } else { $b += 'unverified' }
    $sa = Get-Val $fm 'stale_after'; if ($sa) { try { if ([DateTime]::Parse($sa, $null, 'AdjustToUniversal') -le $now) { $b += 'STALE' } } catch {} }
    $b -join ' · '
}

$rows = @(); $json = @()
$specs = Get-ChildItem (Join-Path $repo 'features') -Recurse -Filter '*.md' | Where-Object { $_.Name -match '^[A-Z][A-Z0-9]*-\d{3}[a-z]?\.md$' } | Sort-Object Name
foreach ($f in $specs) {
    $id = $f.BaseName
    if ($Scope -and -not $id.StartsWith($Scope)) { continue }
    $t = Read-File $f.FullName; $fm = Get-Fm $t
    $brs = @([regex]::Matches($t, "(?m)^\s*-\s+\*\*(BR-$id-\d+)\*\*") | ForEach-Object { $_.Groups[1].Value } | Select-Object -Unique)
    if (-not $brs) { $brs = @([regex]::Matches($t, "\bBR-$id-\d+\b") | ForEach-Object { $_.Value } | Select-Object -Unique) }
    $wi = Read-File (Join-Path $repo "work-items/$id.yml")
    $ft = Read-File (Join-Path $repo "test-design/features/$id.feature")
    $withStory = @($brs | Where-Object { $wi -match "rule:\s*$([regex]::Escape($_))\b" })
    $withScenario = @($brs | Where-Object { $ft -match "@$([regex]::Escape($_))\b" })
    $stories = ([regex]::Matches($wi, '(?m)^\s+-\s+id:\s*S\d+')).Count
    $scenarios = ([regex]::Matches($ft, '(?m)^\s*Scenario')).Count
    $open = ([regex]::Matches($t, '(?m)^\s*-\s*\[ \]')).Count
    $missingStory = @($brs | Where-Object { $_ -notin $withStory }); $missingScenario = @($brs | Where-Object { $_ -notin $withScenario })
    function Fmt-Missing($list, $total) { if (-not $list) { '-' } elseif ($list.Count -eq $total) { 'all' } else { ($list | ForEach-Object { $_ -replace "^BR-$id-", '' }) -join ', ' } }
    $rows += "| $id | $(Get-Val $fm 'context') | $($brs.Count) | $($withStory.Count) ($stories stories) | $($withScenario.Count) ($scenarios scenarios) | $open | $(Get-Badge $fm) | $(Get-Val $fm 'stale_after') | $(Fmt-Missing $missingStory $brs.Count) | $(Fmt-Missing $missingScenario $brs.Count) |"
    $json += [ordered]@{ id = $id; context = (Get-Val $fm 'context'); rules = $brs.Count; rulesWithStory = $withStory.Count; rulesWithScenario = $withScenario.Count; stories = $stories; scenarios = $scenarios; openQuestions = $open; badge = (Get-Badge $fm); staleAfter = (Get-Val $fm 'stale_after'); rulesWithoutStory = $missingStory; rulesWithoutScenario = $missingScenario }
}

$calcRows = @()
foreach ($c in Get-ChildItem (Join-Path $repo 'domain/calculations') -Filter '*.md' | Where-Object { $_.Name -notmatch '^(_?template|index)\.md$' } | Sort-Object Name) {
    $t = Read-File $c.FullName; $fm = Get-Fm $t
    $examples = ([regex]::Matches((($t -split '## Worked examples')[-1] -split '(?m)^#')[0], '(?m)^\|\s*\d+\s*\|')).Count
    $audit = if ($t -match '(?m)^## Audit') { 'yes' } else { 'no' }
    $calcRows += "| $($c.BaseName) | $(Get-Val $fm 'used_by') | $examples | $audit | $(Get-Badge $fm) |"
}

$date = $now.ToString('yyyy-MM-dd')
$md = @"
---
type: Document
title: Coverage matrix (BR -> stories -> scenarios)
description: Which business rules of each feature spec are covered by Jira stories and Gherkin scenarios, with trust badges; generated analytics for the analyst agent.
tags: [analytics, generated]
status: stable
generated: { by: process:coverage-matrix, at: $date }
stale_after: $($now.AddDays(14).ToString('yyyy-MM-dd'))T00:00:00Z
---
# Coverage matrix

> Generated by ``scripts/coverage-matrix.ps1`` on $date$(if ($Scope) { " (scope $Scope)" }). Do not edit by hand.

## Feature specs

| Spec | Context | BRs | with story | with scenario | open questions | badge | stale_after | BR numbers without story | BR numbers without scenario |
|---|---|---|---|---|---|---|---|---|---|
$($rows -join "`n")

## Calculations

| Calculation | used_by | worked examples | audited | badge |
|---|---|---|---|---|
$($calcRows -join "`n")

Spec coverage of the code (``spec + code`` / ``code only`` / ``spec only``): see ``generated/graph/REPO_MAP.md``.
"@
$outPath = Join-Path $repo $Out
$dir = Split-Path $outPath -Parent; if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
[IO.File]::WriteAllText($outPath, $md, $Utf8)
[IO.File]::WriteAllText(($outPath -replace '\.md$', '.json'), (($json | ForEach-Object { [pscustomobject]$_ }) | ConvertTo-Json -Depth 4), $Utf8)
Write-Host "coverage-matrix: $($rows.Count) spec(s), $($calcRows.Count) calculation(s) -> $Out" -ForegroundColor Green
