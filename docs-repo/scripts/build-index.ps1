<#
.SYNOPSIS
  Regenerates OKF index.md files (progressive disclosure, §8) from concept frontmatter.
  Root index.md keeps its okf_version frontmatter and a hand-written "Start here" block between markers.
.EXAMPLE
  .\build-index.ps1            # rewrite all indexes
  .\build-index.ps1 -Check     # exit 1 if any index is out of date (CI)
#>
param(
    [string]$Path = (Split-Path $PSScriptRoot -Parent),
    [switch]$Check,
    [string[]]$Exclude = @('.github', 'scripts', 'ci-examples', 'third-party', 'node_modules', '.git', 'confluence-import', 'work-items', 'test-design', '.context')
)
[cultureinfo]::CurrentCulture = [cultureinfo]::InvariantCulture   # identical sort order on every machine (ICU + machine culture otherwise)
$root = (Resolve-Path $Path).Path
$now = [DateTime]::UtcNow
$changed = @()

function Get-Fm([string]$file) {
    $t = [IO.File]::ReadAllText($file, [Text.UTF8Encoding]::new($false))
    if ($t -match '(?s)\A\uFEFF?---\r?\n(.*?)\r?\n---') { return $Matches[1] }
    return ''
}
function Get-Val([string]$fm, [string]$k) { if ($fm -match "(?m)^$k`:\s*(.+?)\s*$") { return $Matches[1].Trim().Trim('"').Trim("'") } ; return '' }
function Get-Badges([string]$fm) {
    $b = @()
    $status = Get-Val $fm 'status'; if ($status -and $status -ne 'stable') { $b += $status }
    if ($fm -match '(?m)^verified:') { $b += if ($fm -match 'verified:[\s\S]*?by:\s*human:') { 'human-reviewed' } else { 'machine-confirmed' } } else { $b += 'unverified' }
    $sa = Get-Val $fm 'stale_after'
    if ($sa -and ([DateTime]::Parse($sa, $null, 'AdjustToUniversal') -le $now)) { $b += 'STALE' }
    return ($b -join ' · ')
}
function Build-Dir([string]$dir) {
    $rel = $dir.Substring($root.Length).TrimStart('\')
    $lines = @()
    $title = if ($rel) { (Split-Path $rel -Leaf) } else { 'Bundle root' }
    $lines += "# $title"
    $lines += ''
    $subs = Get-ChildItem $dir -Directory | Where-Object { $rd = $_.FullName.Substring($root.Length).TrimStart('\'); -not ($Exclude | Where-Object { $rd -eq $_ -or $rd -like "$_\*" }) } | Sort-Object Name
    $subs = $subs | Where-Object { Get-ChildItem $_.FullName -Recurse -Filter '*.md' | Where-Object { $_.Name -notin 'index.md','log.md','AGENTS.md' } | Select-Object -First 1 }
    $concepts = Get-ChildItem $dir -File -Filter '*.md' | Where-Object { $_.Name -notin 'index.md', 'log.md', 'AGENTS.md' -and $_.Name -notmatch '^_?template' } | Sort-Object Name
    if ($subs) {
        $lines += '# Sections'
        foreach ($s in $subs) {
            $n = (Get-ChildItem $s.FullName -Recurse -Filter '*.md' | Where-Object { $_.Name -notin 'index.md','log.md','AGENTS.md' -and $_.Name -notmatch '^_?template' }).Count
            $lines += "* [$($s.Name)]($($s.Name)/) - $n concept(s)"
        }
        $lines += ''
    }
    if ($concepts) {
        $lines += '# Concepts'
        foreach ($c in $concepts) {
            $fm = Get-Fm $c.FullName
            $t = Get-Val $fm 'title'; if (-not $t) { $t = $c.BaseName }
            $d = Get-Val $fm 'description'
            $badges = Get-Badges $fm
            $lines += "* [$t]($($c.Name)) - $d · $badges"
        }
        $lines += ''
    }
    return ,$lines
}

$dirs = @($root) + (Get-ChildItem $root -Recurse -Directory | Where-Object {
    $rd = $_.FullName.Substring($root.Length).TrimStart('\'); -not ($Exclude | Where-Object { $rd -eq $_ -or $rd -like "$_\*" }) } | ForEach-Object FullName)

foreach ($d in $dirs) {
    $hasConcepts = Get-ChildItem $d -Recurse -Filter '*.md' | Where-Object { $_.Name -notin 'index.md','log.md','AGENTS.md' } | Select-Object -First 1
    if (-not $hasConcepts) { continue }
    $body = Build-Dir $d
    $indexPath = Join-Path $d 'index.md'
    $head = ''
    if ($d -eq $root) {
        $existing = if (Test-Path $indexPath) { [IO.File]::ReadAllText($indexPath, [Text.UTF8Encoding]::new($false)) } else { '' }
        $fm = if ($existing -match '(?s)\A(---\r?\n.*?\r?\n---\r?\n)') { $Matches[1] } else { "---`nokf_version: `"0.2`"`n---`n" }
        $manual = if ($existing -match '(?s)(<!-- manual:start -->.*?<!-- manual:end -->)') { $Matches[1] } else { "<!-- manual:start -->`n# Start here`n* [Glossary](domain/glossary.md) - canonical terms`n* [Codebase map](generated/codebase-map.md) - module → responsibility → entry files`n<!-- manual:end -->" }
        $head = $fm + "`n" + $manual + "`n`n"
        $body = $body | Where-Object { $_ -ne '# Bundle root' }
        $body = @('# Harbor documentation bundle', '') + $body
    }
    $new = $head + (($body -join "`n").TrimEnd()) + "`n<!-- generated by scripts/build-index.ps1 -->`n"
    $old = if (Test-Path $indexPath) { [IO.File]::ReadAllText($indexPath, [Text.UTF8Encoding]::new($false)) } else { '' }
    if ($old -ne $new) {
        $changed += $indexPath.Substring($root.Length).TrimStart('\')
        if (-not $Check) { [IO.File]::WriteAllText($indexPath, $new, [Text.UTF8Encoding]::new($false)) }
    }
}
if ($Check) { if ($changed) { $changed | ForEach-Object { Write-Host "OUT OF DATE $_" -ForegroundColor Yellow }; exit 1 }; Write-Host 'Indexes up to date'; exit 0 }
Write-Host "Indexes written: $($changed.Count)"; $changed | ForEach-Object { "  $_" }


